// ===== ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ =====
function setupSimpleChoice(correctAnswer, onSuccessCallback = null) {
  let selected = null;
  const buttons = document.querySelectorAll(".option-btn");
  
  buttons.forEach(btn => {
    btn.onclick = () => {
      buttons.forEach(b => b.classList.remove("selected"));
      btn.classList.add("selected");
      selected = btn.dataset.answer;
    };
  });
  
  const checkBtn = document.getElementById("checkBtn");
  if (checkBtn) {
    checkBtn.onclick = () => {
      if (!selected) {
        showToast("Выбери ответ!", "error");
        return;
      }
      if (selected === correctAnswer) {
        successAction();
        if (onSuccessCallback) onSuccessCallback();
      } else {
        failAction();
      }
    };
  }
}

function setupCheckboxAnswers(questions) {
  const checkBtn = document.getElementById("checkAnswers");
  if (!checkBtn) return;
  
  checkBtn.onclick = () => {
    const inputs = document.querySelectorAll(".option-item input");
    let allCorrect = true;
    
    inputs.forEach((input, i) => {
      const isChecked = input.checked;
      const isCorrect = questions[i].correct;
      const parent = input.parentElement;
      
      parent.classList.remove("correct", "wrong");
      
      if (isCorrect) {
        parent.classList.add("correct");
      }
      
      if (isChecked && !isCorrect) {
        parent.classList.add("wrong");
        allCorrect = false;
      }
      
      if (!isChecked && isCorrect) {
        allCorrect = false;
      }
    });
    
    if (allCorrect) {
      successAction();
    } else {
      failAction();
    }
  };
}

// ===== ФИДЖИТАЛ С ПАРОЛЕМ =====
function showParentPasswordModal(onSuccess) {
  pendingPhygitalSuccess = onSuccess;
  const modal = document.getElementById("parentPasswordModal");
  const input = document.getElementById("parentPasswordInput");
  const submitBtn = document.getElementById("submitParentPassword");
  const closeBtn = document.getElementById("closePasswordModal");
  
  if (input) input.value = "";
  
  const handleSubmit = () => {
    const password = input ? input.value : "";
    if (password === "umnye2024") {
      modal.style.display = "none";
      if (pendingPhygitalSuccess) {
        pendingPhygitalSuccess();
        pendingPhygitalSuccess = null;
      }
      showToast("✅ Задание подтверждено! Молодец!", "success");
    } else {
      showToast("❌ Неверный пароль! Попроси помощи у родителей", "error");
    }
  };
  
  submitBtn.onclick = handleSubmit;
  if (closeBtn) closeBtn.onclick = () => { modal.style.display = "none"; };
  
  modal.style.display = "block";
  
  // Enter на клавиатуре
  if (input) {
    input.onkeypress = (e) => {
      if (e.key === "Enter") handleSubmit();
    };
  }
}

