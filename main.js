// ===== 1. ИГРА НА РЕАКЦИЮ (КНОПКА В РАЗНЫХ МЕСТАХ) =====
function renderReactionGame() {
  let hits = 0;
  let active = false;
  let timeout = null;
  let startTime = null;
  const requiredHits = state.level === 1 ? 5 : state.level === 2 ? 10 : 15;
  
  // Получаем рекорд
  const reactionRecord = localStorage.getItem(`reaction_record_${state.level}`);
  
  gameArea.innerHTML = `
    <div class="attention-hud">
      <div>🏆 Очки: <b id="score">${state.score}</b></div>
      <div>🔥 Комбо: <b id="combo">${state.combo}</b></div>
      <div>🎯 Серия: <b id="streak">${state.streak}/5</b></div>
    </div>
    <div class="task-title">⚡ Успей нажать! ${'⭐'.repeat(state.level)}</div>
    <div class="reaction-stats">
      <div>🎯 Попаданий: <span id="hitCount">0</span> / ${requiredHits}</div>
      <div>⏱️ Время реакции: <span id="reactionTime">0</span> мс</div>
      <div>🏆 Рекорд: <span id="reactionRecord">${reactionRecord ? reactionRecord + ' мс' : '—'}</span></div>
    </div>
    <div class="reaction-field" id="reactionField">
      <div class="reaction-placeholder">🎯 Нажми "Старт"</div>
    </div>
    <div style="display: flex; justify-content: center; margin-top: 20px; gap: 15px;">
      <button id="startReactionBtn" class="btn-primary" style="width: auto; padding: 12px 32px;">▶️ Старт</button>
    </div>
  `;
  
  updateHUD();
  
  const field = document.getElementById('reactionField');
  const startBtn = document.getElementById('startReactionBtn');
  const hitsSpan = document.getElementById('hitCount');
  const timeSpan = document.getElementById('reactionTime');
  const recordSpan = document.getElementById('reactionRecord');
  
  function saveRecord(ms) {
    const current = localStorage.getItem(`reaction_record_${state.level}`);
    if (!current || ms < parseInt(current)) {
      localStorage.setItem(`reaction_record_${state.level}`, ms);
      if (recordSpan) recordSpan.textContent = ms + ' мс (НОВЫЙ!)';
      return true;
    }
    return false;
  }
  
  function showTarget() {
    if (!active) return;
    
    field.innerHTML = '<div class="reaction-placeholder">👀 Жди...</div>';
    
    const delay = Math.random() * 1500 + 500;
    
    timeout = setTimeout(() => {
      if (!active) return;
      
      const rect = field.getBoundingClientRect();
      const size = 80;
      const maxX = Math.max(0, rect.width - size - 20);
      const maxY = Math.max(0, rect.height - size - 20);
      const x = 10 + Math.random() * maxX;
      const y = 10 + Math.random() * maxY;
      
      const target = document.createElement('div');
      target.className = 'reaction-target';
      target.textContent = '🎯';
      target.style.left = x + 'px';
      target.style.top = y + 'px';
      
      startTime = Date.now();
      
      target.onclick = (e) => {
        e.stopPropagation();
        if (!active) return;
        
        const reactionMs = Date.now() - startTime;
        hits++;
        hitsSpan.textContent = hits;
        timeSpan.textContent = reactionMs;
        
        target.remove();
        
        if (hits >= requiredHits) {
          active = false;
          if (timeout) clearTimeout(timeout);
          field.innerHTML = '<div class="reaction-placeholder">🎉 ПОБЕДА! 🎉</div>';
          startBtn.disabled = false;
          startBtn.style.opacity = '1';
          startBtn.textContent = '▶️ Ещё раз';
          successAction();
          showResult(`✅ Отлично! ${requiredHits} попаданий!`, true);
        } else {
          showTarget();
        }
      };
      
      field.appendChild(target);
      
      const disappearTimeout = setTimeout(() => {
        if (target.parentNode && active) {
          target.remove();
          showTarget();
        }
      }, 1500);
      
      target.dataset.timeout = disappearTimeout;
    }, delay);
  }
  
  startBtn.onclick = () => {
    if (active) return;
    hits = 0;
    active = true;
    hitsSpan.textContent = '0';
    timeSpan.textContent = '0';
    startBtn.disabled = true;
    startBtn.style.opacity = '0.5';
    startBtn.textContent = '🎮 Игра идёт...';
    showTarget();
  };
}

